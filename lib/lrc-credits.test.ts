import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { parseLrc, serializeLrc } from './lrc-timing.ts';
import { isPossibleGeneratorCredit, moveCreditToMetadata } from './lrc-credits.ts';

describe('Imported generator credit review', () => {
  it('flags an isolated generator URL but not ordinary lyrics', () => {
    assert.equal(isPossibleGeneratorCredit('www LRCgenerator com'), true);
    assert.equal(isPossibleGeneratorCredit('www.LRCgenerator.com'), true);
    assert.equal(isPossibleGeneratorCredit('Generated by www.example.com'), true);
    assert.equal(isPossibleGeneratorCredit('I found a website and left it behind'), false);
    assert.equal(isPossibleGeneratorCredit('Love you more than my phone'), false);
  });

  it('only moves an explicitly selected credit, preserving its source and time', () => {
    const document = parseLrc('[ti:My song]\n[00:12.00]This is mine\n[04:37.76]www LRCgenerator com\n');
    const moved = moveCreditToMetadata(document, 1);
    assert.equal(document.lines.length, 2, 'original immutable');
    assert.deepEqual(moved.lines.map(l => l.text), ['This is mine']);
    assert.ok(moved.metadata.includes('[credit:277.76s www LRCgenerator com]'));
    assert.deepEqual(parseLrc(serializeLrc(moved)), moved);
  });

  it('does not silently remove lines or alter ordinary lyrics', () => {
    const document = parseLrc('[00:01.00]I saw a website\n');
    assert.equal(moveCreditToMetadata(document, 0), document);
    assert.equal(moveCreditToMetadata(document, 12), document);
  });
});
